-- Skyline Ops Supabase schema
-- Run this once in Supabase SQL Editor before enabling cloud sync.

create table if not exists public.flights (
  id text primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  number text not null,
  route text,
  aircraft text,
  departure timestamptz,
  status text not null
);

create table if not exists public.aircraft (
  id text primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  tail text not null,
  model text not null,
  capacity integer not null default 0,
  status text not null,
  hours numeric not null default 0
);

create table if not exists public.crew (
  id text primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  role text not null,
  status text not null,
  hours numeric not null default 0,
  flight text
);

create table if not exists public.routes (
  id text primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  code text not null,
  origin text not null,
  dest text not null,
  distance numeric not null default 0
);

create table if not exists public.bookings (
  id text primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  passenger text not null,
  flight text,
  seat text not null,
  cls text not null,
  price numeric not null default 0
);

create table if not exists public.activity (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  text text not null,
  time text not null
);

alter table public.flights enable row level security;
alter table public.aircraft enable row level security;
alter table public.crew enable row level security;
alter table public.routes enable row level security;
alter table public.bookings enable row level security;
alter table public.activity enable row level security;

do $$
declare
  table_name text;
begin
  foreach table_name in array array['flights', 'aircraft', 'crew', 'routes', 'bookings', 'activity'] loop
    execute format('drop policy if exists "Users manage own %I" on public.%I', table_name, table_name);
    execute format('create policy "Users manage own %I" on public.%I for all using (auth.uid() = user_id) with check (auth.uid() = user_id)', table_name, table_name);
  end loop;
end $$;

grant select, insert, update, delete on public.flights, public.aircraft, public.crew, public.routes, public.bookings, public.activity to authenticated;
grant usage, select on sequence public.activity_id_seq to authenticated;
